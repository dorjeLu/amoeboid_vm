//! `host.nix`: the guest account, the flake's `host` input; rendered on every start.

use std::fmt;

use crate::domain::{Gid, GuestHome, Uid, UserName};

/// A Nix double-quoted string literal. Escaping is the only constructor, so it is the only way text
/// enters generated Nix: `\`, `"` and `${` are escaped.
#[derive(Clone, PartialEq, Eq, Hash, Debug)]
pub struct NixString(String);

impl NixString {
    /// `text` as a Nix string literal, quotes included.
    #[must_use]
    pub fn escape(text: &str) -> Self {
        let mut out = String::with_capacity(text.len().saturating_add(2));
        out.push('"');
        let mut chars = text.chars().peekable();
        while let Some(ch) = chars.next() {
            match ch {
                '\\' => out.push_str("\\\\"),
                '"' => out.push_str("\\\""),
                '$' if chars.peek() == Some(&'{') => out.push_str("\\$"),
                other => out.push(other),
            }
        }
        out.push('"');
        Self(out)
    }

    #[must_use]
    pub fn as_str(&self) -> &str {
        &self.0
    }
}

impl fmt::Display for NixString {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(&self.0)
    }
}

/// The text of `host.nix`.
#[derive(Clone, PartialEq, Eq, Debug)]
pub struct HostModule(String);

impl HostModule {
    #[must_use]
    pub fn as_str(&self) -> &str {
        &self.0
    }
}

/// The guest account: user, ids and home (the host's, so paths paste across).
#[must_use]
pub fn host_module(user: &UserName, uid: Uid, gid: Gid, home: &GuestHome) -> HostModule {
    let user = NixString::escape(user.get());
    let home = NixString::escape(home.get().get());
    HostModule(format!(
        "\
# Generated by amoeboid from run_config.kdl and $HOME on every start; edits here are lost.
{{ ... }}:

{{
  amoeboid.user = {user};
  amoeboid.uid = {uid};
  amoeboid.gid = {gid};
  amoeboid.home = {home};
}}
"
    ))
}

#[cfg(test)]
#[cfg_attr(coverage_nightly, coverage(off))]
mod tests {
    use serde_json::Value;

    use super::*;
    use crate::domain::HomeDir;
    use crate::testing;

    #[test]
    fn nix_strings_escape_backslash_quote_and_interpolation_only() {
        let cases: Vec<(&str, String)> = [
            ("", r#""""#),
            ("/home/alice", r#""/home/alice""#),
            (r"a\b", r#""a\\b""#),
            (r#"a"b"#, r#""a\"b""#),
            ("${x}", r#""\${x}""#),
            ("$x", r#""$x""#),
            ("$", r#""$""#),
            ("a$/{x", r#""a$/{x""#),
            ("$${", r#""$\${""#),
            (r"a\${b}", r#""a\\\${b}""#),
            ("it's ''", r#""it's ''""#),
            ("日本 🚀", r#""日本 🚀""#),
        ]
        .into_iter()
        .map(|(text, nix): (&str, &str)| (text, nix.to_owned()))
        .collect();
        testing::table(&cases, |text| {
            let nix = NixString::escape(text);
            assert_eq!(nix.to_string(), nix.as_str());
            nix.as_str().to_owned()
        });
    }

    #[test]
    fn host_modules_match_the_python_ones() {
        let cases = testing::golden_cases("host_nix", "json", "nix").unwrap();
        assert!(cases.len() > 1);
        for case in cases {
            let input: Value = serde_json::from_str(&case.input).unwrap();
            let text = |key: &str| input.get(key).and_then(Value::as_str).unwrap().to_owned();
            let id =
                |key: &str| u32::try_from(input.get(key).and_then(Value::as_u64).unwrap()).unwrap();
            let home = GuestHome::parse(HomeDir::parse(text("home")).unwrap()).unwrap();
            let module = host_module(
                &UserName::parse(text("user")).unwrap(),
                Uid::parse(id("uid")).unwrap(),
                Gid::parse(id("gid")).unwrap(),
                &home,
            );
            assert_eq!(module.as_str(), case.output, "{}", case.name);
        }
    }
}
