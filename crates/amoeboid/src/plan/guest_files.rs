//! What the host puts in the guest's home about its NixOS configuration: the VM's own copy, the
//! reference copy of what is running, and a README. Pure: the files are values; delivery decides
//! how they get there (`GuestDelivery`).
//!
//! ```text
//! <state>/nix/ + host.nix  --first run-->  home/amoeboid/nix/        (the VM's own, editable copy)
//! <state>/nix/ + host.nix  --every start-> home/amoeboid/reference/  (what is running)
//!                          --every start-> home/amoeboid/README.md
//! ```

use crate::domain::{FileMode, GuestDest, GuestFile, GuestRel, TreeFile};
use crate::layout::HOST_MODULE;
use crate::plan::host_nix::HostModule;
use crate::refined;

/// The text of `home/amoeboid/README.md` (the same as the Python launcher's).
pub const GUEST_README: &str = r"# This VM's NixOS configuration

- `nix/` is your own copy of the configuration this VM was created from: the flake,
  `base.nix` (user, shares, ssh, console), `recipe.nix` (packages, services, tweaks)
  and `host.nix` (your account, generated by the host and passed in as the `host` input).
  Edit it freely; amoeboid never overwrites or reads it. Changes there are not applied
  automatically: whoever runs this VM decides when and how to adopt them.
- `reference/` is the configuration this VM is actually running. It is rewritten on
  every start, so edits there are lost; diff your copy against it to see your changes.

The Nix store is read-only inside this VM, so nothing can be installed through Nix from
here, and anything installed outside your home directory is gone after a restart. Find
packages with `nixpkgs-search REGEX` (it searches the exact nixpkgs this VM uses), then
add them to `nix/recipe.nix`.
";

/// Mode of the copies: like any file the launcher writes.
const MODE: FileMode = refined!(FileMode, 0o644);

/// A directory of the share and the files that make it up, `dest` relative to `dir` (the shape
/// `GuestDelivery::replace_tree` takes).
#[derive(Clone, PartialEq, Eq, Debug)]
pub struct GuestTree {
    pub dir: GuestRel,
    pub files: Vec<GuestFile>,
}

/// The configuration files for the guest's home.
#[derive(Clone, PartialEq, Eq, Debug)]
pub struct GuestCopies {
    /// The VM's own, editable copy. Delivered when the VM is created or rebased; otherwise left
    /// alone, because the guest edits it.
    pub own: GuestTree,
    /// What the VM runs; replaced on every start.
    pub reference: GuestTree,
    pub readme: GuestFile,
}

/// The copies of the VM's configuration `tree` (its regular files) with the generated `host.nix`
/// in both; a `host.nix` in the tree is replaced.
#[must_use]
pub fn guest_copies(tree: &[TreeFile], host: &HostModule) -> GuestCopies {
    let host_rel = GuestRel::of(&HOST_MODULE);
    let mut files: Vec<GuestFile> = tree
        .iter()
        .map(|file| GuestFile {
            dest: file.rel.clone(),
            bytes: file.bytes.clone(),
            mode: MODE,
        })
        .collect();
    let generated = GuestFile {
        dest: host_rel.clone(),
        bytes: host.as_str().as_bytes().to_vec(),
        mode: MODE,
    };
    match files.iter_mut().find(|file| file.dest == host_rel) {
        Some(slot) => *slot = generated,
        None => files.push(generated),
    }
    GuestCopies {
        own: GuestTree {
            dir: GuestDest::own_dir(),
            files: files.clone(),
        },
        reference: GuestTree {
            dir: GuestDest::reference_dir(),
            files,
        },
        readme: GuestDest::Readme.file(GUEST_README.as_bytes().to_vec(), MODE),
    }
}

#[cfg(test)]
#[cfg_attr(coverage_nightly, coverage(off))]
mod tests {
    use super::*;
    use crate::domain::{Gid, GuestHome, HomeDir, Observation, Uid, UserName};
    use crate::plan::host_module;

    fn rel(text: &str) -> GuestRel {
        GuestRel::parse(text.to_owned()).unwrap()
    }

    fn tree_file(path: &str, text: &str) -> TreeFile {
        TreeFile {
            rel: rel(path),
            bytes: text.as_bytes().to_vec(),
        }
    }

    fn file(path: &str, text: &str) -> GuestFile {
        GuestFile {
            dest: rel(path),
            bytes: text.as_bytes().to_vec(),
            mode: MODE,
        }
    }

    fn host() -> HostModule {
        let home = HomeDir::parse("/home/u".to_owned()).unwrap();
        let guest_home = GuestHome::observe(&home, |dir| Observation::Directory {
            resolved: dir.clone(),
        })
        .unwrap();
        host_module(
            &UserName::parse("u".to_owned()).unwrap(),
            Uid::parse(1000).unwrap(),
            Gid::parse(100).unwrap(),
            &guest_home,
        )
    }

    #[test]
    fn the_readme_is_the_text_the_python_launcher_wrote() {
        assert_eq!(
            GUEST_README,
            include_str!("../../tests/golden/guest_readme.md")
        );
    }

    #[test]
    fn the_copies_are_the_tree_plus_the_generated_host_module_in_two_places() {
        let host = host();
        let generated = file("host.nix", host.as_str());
        let tree = [
            tree_file("base.nix", "base"),
            tree_file("flake.nix", "flake"),
            tree_file("sub/recipe.nix", "recipe"),
        ];
        let files = vec![
            file("base.nix", "base"),
            file("flake.nix", "flake"),
            file("sub/recipe.nix", "recipe"),
            generated,
        ];
        assert_eq!(
            guest_copies(&tree, &host),
            GuestCopies {
                own: GuestTree {
                    dir: rel("home/amoeboid/nix"),
                    files: files.clone(),
                },
                reference: GuestTree {
                    dir: rel("home/amoeboid/reference"),
                    files,
                },
                readme: GuestFile {
                    dest: rel("home/amoeboid/README.md"),
                    bytes: GUEST_README.as_bytes().to_vec(),
                    mode: MODE,
                },
            }
        );
    }

    #[test]
    fn a_host_module_in_the_tree_is_replaced_in_place() {
        let host = host();
        let tree = [
            tree_file("a", "1"),
            tree_file("host.nix", "stale"),
            tree_file("z", "2"),
        ];
        let copies = guest_copies(&tree, &host);
        assert_eq!(
            copies.own.files,
            vec![
                file("a", "1"),
                file("host.nix", host.as_str()),
                file("z", "2")
            ]
        );
        assert_eq!(copies.own.files, copies.reference.files);
    }

    #[test]
    fn an_empty_tree_still_gets_the_host_module() {
        let host = host();
        assert_eq!(
            guest_copies(&[], &host).own.files,
            vec![file("host.nix", host.as_str())]
        );
    }
}
