/// Whether `ch` must be escaped rather than written literally in a KDL string.
pub(super) fn is_nonprintable(ch: char) -> bool {
    let code = u32::from(ch);
    RANGES
        .binary_search_by(|&(first, last)| {
            if code < first {
                Ordering::Greater
            } else if code > last {
                Ordering::Less
            } else {
                Ordering::Equal
            }
        })
        .is_ok()
}

#[cfg(test)]
#[cfg_attr(coverage_nightly, coverage(off))]
mod tests {
    use super::*;
    use crate::testing;

    const GOLDEN: &str = include_str!("../../tests/golden/kdl_nonprintable.json");

    fn golden_ranges() -> Vec<(u32, u32)> {
        let json: serde_json::Value = serde_json::from_str(GOLDEN).unwrap();
        json.get("ranges")
            .and_then(serde_json::Value::as_array)
            .unwrap()
            .iter()
            .map(|pair| {
                let pair = pair.as_array().unwrap();
                let end = |i: usize| pair.get(i).and_then(serde_json::Value::as_u64).unwrap();
                (
                    u32::try_from(end(0)).unwrap(),
                    u32::try_from(end(1)).unwrap(),
                )
            })
            .collect()
    }

    #[test]
    fn table_equals_the_python_golden_ranges() {
        assert_eq!(RANGES, golden_ranges());
    }

    #[test]
    fn table_is_sorted_and_disjoint() {
        for (i, pair) in RANGES.windows(2).enumerate() {
            let (a, b) = (pair.first().unwrap(), pair.get(1).unwrap());
            assert!(a.0 <= a.1, "range {i} is inverted");
            assert!(a.1 < b.0, "range {i} overlaps the next");
        }
    }

    #[test]
    fn characters_on_each_side_of_range_edges_are_classified() {
        testing::table(
            &[
                ('\u{0}', true),
                ('\u{1f}', true),
                (' ', false),
                ('a', false),
                ('~', false),
                ('\u{7f}', true),
                ('\u{a0}', true),
                ('\u{a1}', false),
                ('\u{ad}', true),
                ('\u{ae}', false),
                ('é', false),
                ('\u{200b}', true),
                ('\u{2028}', true),
                ('\u{3000}', true),
                ('\u{e000}', true),
                ('\u{f8ff}', true),
                ('\u{feff}', true),
                ('\u{fffe}', true),
                ('\u{ffff}', true),
                ('\u{1f600}', false),
                ('\u{e0001}', true),
                ('\u{10ffff}', true),
            ],
            |ch| is_nonprintable(*ch),
        );
    }

    #[test]
    fn range_edges_and_their_neighbours_agree_with_a_linear_scan() {
        let linear = |ch: char| {
            let code = u32::from(ch);
            RANGES
                .iter()
                .any(|&(first, last)| (first..=last).contains(&code))
        };
        for &(first, last) in RANGES {
            for code in [first.saturating_sub(1), first, last, last.saturating_add(1)] {
                if let Some(ch) = char::from_u32(code) {
                    assert_eq!(is_nonprintable(ch), linear(ch), "U+{code:04X}");
                }
            }
        }
    }
}
