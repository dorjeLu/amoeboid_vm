"""What a VM is built from, and the one part of it the VM may ask to change.

Host-owned, never read back from the guest: the recipe (`--recipe`, else `recipe` from
the config, else the bundled one), the host module, the flake and base.nix. The guest
gets copies under `~/amoeboid/reference/`, rewritten on every start, for reading.

Guest-owned: `~/amoeboid/packages.kdl`, a list of nixpkgs attribute names. On each start
the host reads it without following symlinks, keeps only well-formed names, and renders
them into a module that can do nothing but add those packages. Anything else about the
VM (services, shares, how qemu is launched) changes only when the host user edits a
host-side file. That matters because the whole definition is evaluated into the qemu
runner, which runs on the host as the user.
"""

import logging
import re
from dataclasses import dataclass
from pathlib import Path

from amoeboid import guestfs
from amoeboid.errors import AppError, because
from amoeboid.guestfs import Tree
from amoeboid.kdl_serde import KdlSerde
from amoeboid.paths import BUNDLED_NIX, VmPaths
from amoeboid.result import Err, Ok, Result, attempt, railway

log = logging.getLogger(__name__)

GUEST_DIR = "home/amoeboid"
GUEST_PACKAGES = f"{GUEST_DIR}/packages.kdl"
GUEST_REFERENCE = f"{GUEST_DIR}/reference"

MAX_PACKAGES = 256
MAX_PACKAGES_BYTES = 64 * 1024
_ATTR_PART = r"[A-Za-z_][A-Za-z0-9_'-]*"
_ATTR = re.compile(rf"{_ATTR_PART}(\.{_ATTR_PART}){{0,7}}")

PACKAGES_TEMPLATE = """\
// Extra nixpkgs packages for this VM, by attribute name; find them with
// `nixpkgs-search REGEX`. They are installed the next time the VM is started from
// the host. Unknown names are skipped with a warning on the host.
(list)packages {
}
"""


def packages_module_path(vm: VmPaths) -> Path:
    return vm.state / "packages.nix"


@dataclass(frozen=True, slots=True)
class Requested:
    packages: tuple[str, ...]
    problems: tuple[str, ...]


def parse_packages(text: str) -> Requested:
    """Pure: the valid attribute names in a packages.kdl, and what was wrong with the rest."""
    match KdlSerde.loads(text):
        case Err(error):
            return Requested((), (error,))
        case Ok({"packages": list(items), **rest}) if not rest:
            pass
        case Ok(doc) if not doc:
            return Requested((), ())
        case Ok(_):
            return Requested((), ('expected only a `(list)packages { - "name" }` node',))
    names: list[str] = []
    problems: list[str] = []
    for item in items:
        if not isinstance(item, str) or not _ATTR.fullmatch(item):
            problems.append(f"{item!r} isn't a nixpkgs attribute name")
        elif item not in names:
            names.append(item)
    if len(names) > MAX_PACKAGES:
        problems.append(f"more than {MAX_PACKAGES} packages; using the first {MAX_PACKAGES}")
        names = names[:MAX_PACKAGES]
    return Requested(tuple(names), tuple(problems))


def render_packages_module(names: tuple[str, ...]) -> str:
    """Pure: a NixOS module adding exactly these packages, skipping names nixpkgs lacks."""
    # Names are restricted to identifier characters, but quote properly regardless.
    listed = " ".join(_nix_string(n) for n in names)
    return f"""\
# Generated by amoeboid from the VM's ~/amoeboid/packages.kdl on every start.
{{ lib, pkgs, ... }}:

let
  wanted = [ {listed} ];
  resolve = name:
    let found = lib.attrByPath (lib.splitString "." name) null pkgs;
    in if lib.isDerivation found then found
       else lib.warn "amoeboid: '${{name}}' is not a package in nixpkgs; skipped" null;
in
{{
  environment.systemPackages = builtins.filter (p: p != null) (map resolve wanted);
}}
"""


def _nix_string(s: str) -> str:
    escaped = s.replace("\\", "\\\\").replace('"', '\\"').replace("${", "\\${")
    return f'"{escaped}"'


@railway
def prepare_packages(vm: VmPaths) -> Result[Path, AppError]:
    """Render the guest's package requests into a host-side module; seed the file if absent."""
    raw = guestfs.read_file(vm.guest, GUEST_PACKAGES, MAX_PACKAGES_BYTES).or_bail()
    if raw is None:
        guestfs.replace_file(vm.guest, GUEST_PACKAGES, PACKAGES_TEMPLATE.encode()).or_bail()
        requested = Requested((), ())
    else:
        requested = parse_packages(raw.decode(errors="replace"))
    for problem in requested.problems:
        log.warning("~/amoeboid/packages.kdl in '%s': %s", vm.name, problem)
    if requested.packages:
        log.info("extra packages requested by '%s': %s", vm.name, " ".join(requested.packages))
    target = packages_module_path(vm)
    module = render_packages_module(requested.packages)

    def write() -> Path:
        target.write_text(module)
        return target

    return attempt(write, because(f"can't write {target}"))


@railway
def publish_reference(vm: VmPaths, recipe: Path, host_module: Path) -> Result[None, AppError]:
    """Copy the VM's whole definition into its home for reading; edits there are lost."""
    tree: Tree = {}
    files = {
        "flake.nix": BUNDLED_NIX / "flake.nix",
        "flake.lock": BUNDLED_NIX / "flake.lock",
        "base.nix": BUNDLED_NIX / "base.nix",
        "host.nix": host_module,
        "packages.nix": packages_module_path(vm),
    }
    for name, path in files.items():
        tree[name] = attempt(path.read_bytes, because(f"can't read {path}")).or_bail()
    for rel, data in read_recipe(recipe).or_bail().items():
        tree[f"recipe/{rel}"] = data
    guestfs.replace_tree(vm.guest, GUEST_REFERENCE, tree).or_bail()
    return guestfs.replace_file(vm.guest, f"{GUEST_DIR}/README.md", GUEST_README.encode())


def read_recipe(path: Path) -> Result[Tree, AppError]:
    """A recipe as a tree: a single file becomes default.nix, a directory is taken whole."""

    def read() -> Tree:
        if path.is_file():
            return {"default.nix": path.read_bytes()}
        return {
            f.relative_to(path).as_posix(): f.read_bytes()
            for f in sorted(path.rglob("*"))
            if f.is_file()
        }

    return attempt(read, because(f"can't read recipe {path}"))


GUEST_README = """\
# This VM's NixOS definition

The Nix store is read-only inside this VM, so nothing can be installed through Nix from
here, and anything installed outside your home directory is gone after a restart.

## Getting packages

1. Find the package: `nixpkgs-search REGEX` (searches the exact nixpkgs this VM uses).
2. Add its attribute name to `packages.kdl` in this directory:

       (list)packages {
           - "figlet"
           - "python3Packages.requests"
       }

3. It is installed the next time the VM is started from the host (`amoeboid restart`).
   Rebooting from inside the VM only shuts it down.

## Everything else

`reference/` holds the full definition this VM was built from (the recipe, flake, base
module, host settings, and the module generated from `packages.kdl`). It is rewritten on
every start, so edits there have no effect. Changes beyond packages (services, kernel,
shares) have to be made on the host; describe what you need to the person running the VM.
"""
